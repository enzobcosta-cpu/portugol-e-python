# Exercício 03 — Média de três notas
# Aluno: Enzo Bernardo
# Objetivo: calcular a média de três notas.

# Entrada: vai pegar as três notas do aluno.
n1 = float(input("Digite a primeira nota: "))
n2 = float(input("Digite a segunda nota: "))
n3 = float(input("Digite a terceira nota: "))

# Processamento: somo as notas e divido por três para achar a média.
media = (n1 + n2 + n3) / 3

# Saída: vai mostrar a média encontrada.
print("Média:", media)
